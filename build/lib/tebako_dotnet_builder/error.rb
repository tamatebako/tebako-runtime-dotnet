module TebakoDotnetBuilder
  # The build tooling's single error class: every failure the model
  # raises carries the process exit code it should surface as (named
  # errors and named exit codes, never silent fallbacks — spec 00 §9).
  # tools/build_runtime and tools/boot_smoke map an unhandled Error to
  # stderr + exit(code).
  class Error < StandardError
    attr_reader :exit_code

    def initialize(message, exit_code = 103)
      super(message)
      @exit_code = exit_code
    end
  end
end
